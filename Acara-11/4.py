angka = [3, 5, 8, 1, 2, 9, 7, 4, 6,]
huruf = ['doni','caca','eva','bobi,','ani','faruk']
print(angka)
print(huruf)

# mengurutkan isi list berupa angka dan kata menggunakan sort
print('marilah kita urutkan :')
angka.sort()
huruf.sort()
