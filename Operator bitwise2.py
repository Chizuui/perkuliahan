#operasi OR
c = a | b
print ("a | b = %s" % c)

#operasi XOR
c = a ^ b
print ("a ^ b = %s" % c)

#operasi NOT
c = ~a
print ("~a = %s" % c)
c = ~b
print ("~b = %s" % c)

